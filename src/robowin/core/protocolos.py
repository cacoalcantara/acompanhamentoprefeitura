"""Protocolos congelados (M0)."""
from __future__ import annotations

from collections.abc import Sequence
from typing import Any, Protocol, runtime_checkable

from pydantic import BaseModel

from .tipos import (
    AckOrdem,
    ChamadaLLM,
    ClassificacaoNoticia,
    ComandoOrdem,
    DecisaoRisco,
    EstadoConta,
    EventoNoticia,
    Instrumento,
    Intencao,
    LivroSnapshot,
    Posicao,
    Tick,
    VetorFeatures,
)


@runtime_checkable
class TerminalMT5(Protocol):
    """Subconjunto da API real do pacote MetaTrader5 usado pelo projeto."""
    def initialize(self, **kw: Any) -> bool: ...
    def shutdown(self) -> None: ...
    def last_error(self) -> tuple[int, str]: ...
    def account_info(self) -> Any: ...
    def terminal_info(self) -> Any: ...
    def symbols_get(self, group: str | None = None) -> Sequence[Any] | None: ...
    def symbol_info(self, symbol: str) -> Any: ...
    def symbol_info_tick(self, symbol: str) -> Any: ...
    def symbol_select(self, symbol: str, enable: bool = True) -> bool: ...
    def copy_ticks_from(self, symbol: str, date_from: Any, count: int, flags: int) -> Any: ...
    def copy_ticks_range(self, symbol: str, date_from: Any, date_to: Any, flags: int) -> Any: ...
    def market_book_add(self, symbol: str) -> bool: ...
    def market_book_get(self, symbol: str) -> Any: ...
    def market_book_release(self, symbol: str) -> bool: ...
    def order_check(self, request: dict[str, Any]) -> Any: ...
    def order_send(self, request: dict[str, Any]) -> Any: ...
    def orders_get(self, **kw: Any) -> Any: ...
    def positions_get(self, **kw: Any) -> Any: ...
    def history_orders_get(self, *a: Any, **kw: Any) -> Any: ...
    def history_deals_get(self, *a: Any, **kw: Any) -> Any: ...


class Barramento(Protocol):
    def publicar(self, topico: str, msg: BaseModel | dict[str, Any]) -> None: ...
    def assinar(self, topico: str, cb: Any) -> None: ...


class ArmazemTicks(Protocol):
    def gravar(self, simbolo: str, ticks: Sequence[Tick]) -> int: ...
    def ler(self, simbolo: str, de_ns: int, ate_ns: int) -> list[Tick]: ...


class Banco(Protocol):
    def inserir(self, tabela: str, linha: dict[str, Any]) -> None: ...
    def consultar(self, sql: str, params: tuple[Any, ...] = ()) -> list[dict[str, Any]]: ...


class Braco(Protocol):
    id: str
    def decidir(self, t_ns: int, dossie: dict[str, Any]) -> Intencao | None: ...


class ModeloPreditivo(Protocol):
    nome: str
    status: str
    def prever(self, f: VetorFeatures) -> dict[str, float]: ...


class SinalStatArb(Protocol):
    nome: str
    def sinal(self, t_ns: int, precos: dict[str, float]) -> dict[str, float]: ...


class ProvedorLLM(Protocol):
    nome: str
    async def gerar_estruturado(
        self, *, modelo: str, sistema: str, mensagem: str, schema: type[BaseModel],
        prazo_s: float, effort: str | None = None, max_tokens: int = 4096,
    ) -> tuple[BaseModel | None, ChamadaLLM]: ...


class MotorRisco(Protocol):
    def avaliar(self, intencao: Intencao, posicao: Posicao, t_ns: int) -> DecisaoRisco: ...


class Executor(Protocol):
    def enviar(self, cmd: ComandoOrdem) -> AckOrdem: ...


class PoliticaExecucao(Protocol):
    nome: str
    def escolher(self, estado: dict[str, float]) -> str: ...


class EstrategiaMM(Protocol):
    def cotar(self, t_ns: int, estado: dict[str, float]) -> dict[str, float | None]: ...


class ClassificadorNoticias(Protocol):
    def classificar(self, ev: EventoNoticia) -> ClassificacaoNoticia: ...


class FonteNoticias(Protocol):
    nome: str
    verificado: bool
    def coletar(self) -> list[EventoNoticia]: ...


class RegistroAuditoria(Protocol):
    def registrar(self, tipo: str, dados: dict[str, Any]) -> str: ...


__all__ = [n for n in dir() if n[0].isupper()] + ["EstadoConta", "Instrumento", "LivroSnapshot"]
